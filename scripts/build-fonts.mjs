#!/usr/bin/env node
/**
 * FOSS-Atlas font pipeline
 * ------------------------------------------------------------------
 * Produces a self-hosted, subsetted CJK webfont under public/fonts/, plus the
 * @font-face CSS that loads it.
 *
 * Why self-host at all:
 *   The site is Chinese-first, but fonts.googleapis.com is unreachable from
 *   mainland China. Loading the webfont off the critical path (see index.html)
 *   already avoids a render stall there, but the *typography* upgrade then never
 *   happens for the main audience. Shipping the bytes removes the third-party
 *   dependency entirely.
 *
 * Why a subset and not the whole family:
 *   Noto Sans CJK SC is ~16 MB per weight. The site only ever renders a bounded
 *   set of characters (the catalogue copy + the wiki markdown + the UI strings),
 *   ~1.1k distinct code points. subset-font (harfbuzz) rewrites each weight down
 *   to just those glyphs, turning 16 MB into a few tens of KB.
 *
 * The glyph set is derived from the *current* content at build time, so it must
 * be re-run after adding resources or wiki prose (see README). Anything outside
 * the set falls back to the platform CJK font, which is why the fallback stack
 * in index.css still matters.
 */
import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import subsetFont from 'subset-font'

import { collectGlyphs } from './glyphSet.mjs'

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = resolve(__dirname, '..')
const OUT_DIR = resolve(ROOT, 'public/fonts')
const CACHE_DIR = resolve(ROOT, '.cache/fonts')

/*
 * The three weights the UI actually uses: 400 (body), 500 (medium), 700 (bold).
 * `font-semibold` (600) is declared against the 700 face — see fonts.css below.
 * Noto Sans CJK SC has no 600 weight in this family, and shipping a fourth
 * 16 MB→subset copy for a shade between Medium and Bold is not worth the bytes.
 */
const WEIGHTS = [
  { weight: 400, file: 'NotoSansCJKsc-Regular.otf' },
  { weight: 500, file: 'NotoSansCJKsc-Medium.otf' },
  { weight: 700, file: 'NotoSansCJKsc-Bold.otf' },
]
const SOURCE_URL = (f) =>
  `https://cdn.jsdelivr.net/gh/notofonts/noto-cjk@main/Sans/OTF/SimplifiedChinese/${f}`

/* ---------------------------------------------------------------- *
 * 1. Collect every character the site can render.
 * ---------------------------------------------------------------- *
 * The walk itself lives in scripts/glyphSet.mjs so that scripts/build-og.mjs can
 * check the copy it paints onto the social cards against the same set — see the
 * header there for why sharing it matters.
 */
const glyphs = collectGlyphs()

/* ---------------------------------------------------------------- *
 * 2. Fetch a full source weight into the cache (once).
 * ---------------------------------------------------------------- */
function ensureSource(file) {
  const dest = resolve(CACHE_DIR, file)
  if (existsSync(dest)) return dest
  mkdirSync(CACHE_DIR, { recursive: true })
  execFileSync('curl', ['-sL', '--max-time', '120', '-o', dest, SOURCE_URL(file)], {
    stdio: 'inherit',
  })
  return dest
}

/* ---------------------------------------------------------------- *
 * 3. Subset → woff2, write the faces + a hand-written CSS file.
 * ---------------------------------------------------------------- */
mkdirSync(OUT_DIR, { recursive: true })

const faces = []
for (const { weight, file } of WEIGHTS) {
  const src = ensureSource(file)
  const buf = readFileSync(src)
  const woff2 = await subsetFont(buf, glyphs, { targetFormat: 'woff2' })
  const outName = `noto-sans-sc-${weight}.woff2`
  writeFileSync(resolve(OUT_DIR, outName), woff2)
  faces.push({ weight, outName, bytes: woff2.length })
  process.stdout.write(`  ✓ ${outName}  ${(woff2.length / 1024).toFixed(1)} KB\n`)
}

const css = `/*
 * Self-hosted subset of Noto Sans CJK SC, generated by scripts/build-fonts.mjs.
 * Do not edit by hand — run \`npm run fonts\` after changing site copy.
 *
 * Covers only the ${[...new Set(glyphs)].length} code points the site currently renders; characters
 * outside the set fall back to the platform CJK font declared in index.css.
 */
${faces
  .map(
    ({ weight, outName }) => `@font-face {
  font-family: "Noto Sans SC";
  font-style: normal;
  font-weight: ${weight === 700 ? '600 700' : weight};
  font-display: swap;
  src: url("./${outName}") format("woff2");
}`,
  )
  .join('\n\n')}
`
writeFileSync(resolve(OUT_DIR, 'fonts.css'), css)

const total = faces.reduce((n, f) => n + f.bytes, 0)
console.log(
  `fonts: ${[...new Set(glyphs)].length} glyphs → ${WEIGHTS.length} faces, ${(total / 1024).toFixed(1)} KB total`,
)
